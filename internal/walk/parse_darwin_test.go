func TestParseBulkFixture(t *testing.T) {
	// Captured from getattrlistbulk on a real APFS directory.
	hello := []byte{
		0x50, 0x00, 0x00, 0x00, 0x0d, 0x00, 0x00, 0x82, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
		0x05, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x2c, 0x00, 0x00, 0x00, 0x0a, 0x00, 0x00, 0x00,
		0x10, 0x00, 0x00, 0x01, 0x1a, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x36, 0x92, 0xd4, 0x02,
		0x00, 0x00, 0x00, 0x00, 0x02, 0x00, 0x00, 0x00, 0x00, 0x10, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
		0x00, 0x00, 0x00, 0x00, 0x68, 0x65, 0x6c, 0x6c, 0x6f, 0x2e, 0x74, 0x78, 0x74, 0x00, 0x00, 0x00,
	}
	dir := []byte{
		0x40, 0x00, 0x00, 0x00, 0x0d, 0x00, 0x00, 0x82, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
		0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x20, 0x00, 0x00, 0x00, 0x04, 0x00, 0x00, 0x00,
		0x10, 0x00, 0x00, 0x01, 0x1a, 0x00, 0x00, 0x00, 0x02, 0x00, 0x00, 0x00, 0x35, 0x92, 0xd4, 0x02,
		0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x73, 0x75, 0x62, 0x00, 0x00, 0x00, 0x00, 0x00,
	}
	link := []byte{
		0x50, 0x00, 0x00, 0x00, 0x0d, 0x00, 0x00, 0x82, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
		0x05, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x2c, 0x00, 0x00, 0x00, 0x0a, 0x00, 0x00, 0x00,
		0x10, 0x00, 0x00, 0x01, 0x1a, 0x00, 0x00, 0x00, 0x05, 0x00, 0x00, 0x00, 0x40, 0x95, 0xd4, 0x02,
		0x00, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
		0x00, 0x00, 0x00, 0x00, 0x68, 0x65, 0x6c, 0x6c, 0x6f, 0x2e, 0x6c, 0x6e, 0x6b, 0x00, 0x00, 0x00,
	}
	buf := append(append(hello, dir...), link...)
	ents, err := ParseBulk(buf, 3)
	if err != nil {
		t.Fatal(err)
	}
	if ents[0].Name != "hello.txt" || ents[0].IsDir || ents[0].IsSymlink || ents[0].Allocated != 4096 || ents[0].LinkCount != 2 || ents[0].FileID != 47485494 {
		t.Fatalf("file: %+v", ents[0])
	}
	if ents[1].Name != "sub" || !ents[1].IsDir || ents[1].Allocated != 0 {
		t.Fatalf("dir: %+v", ents[1])
	}
	if ents[2].Name != "hello.lnk" || !ents[2].IsSymlink || ents[2].IsDir || ents[2].Allocated != 0 {
		t.Fatalf("link: %+v", ents[2])
	}
	if ents[0].FSID == 0 || ents[0].FSID != ents[1].FSID {
		t.Fatalf("fsid file=%d dir=%d", ents[0].FSID, ents[1].FSID)
	}
}
